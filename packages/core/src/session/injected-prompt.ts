/**
 * Whether a user turn was typed by the person or put there by the harness, a helper or Memnox, because the prompt
 * hook and the transcript both read those as user turns and only the person's own words may stand as what they asked.
 */

/**
 * Tags that open a whole turn nobody typed. A system reminder is not one: the host wraps it around the person's own
 * prompt, so it is taken off and what follows it is read.
 */
const INJECTED_TAGS = [
  'agent-message',
  'task-notification',
  'command-name',
  'command-message',
  'command-args',
  'local-command-stdout',
  'local-command-stderr',
  'local-command-caveat',
];

/** The name a host tag opens with, read where the scan stands. */
const TAG_NAME = /[a-z_-]+/iy;

/** Lines the harness or Memnox writes at the head of a turn it adds, read case blind. */
const INJECTED_LINES: readonly RegExp[] = [
  /^\[subagent hand-?back\]/i,
  /^another claude session sent a message:?/i,
  /^\[memnox, not the person\]/i,
  /^\[request interrupted by user[^\]]*\]$/i,
  /^caveat: the messages below were generated by the user while running local commands/i,
];

const OPENING_TAG = new RegExp(`^<(${INJECTED_TAGS.join('|')})(\\s|>|/)`, 'i');

/** Origins the transcript stamps on a turn nobody typed; `human` and an absent origin are the person. */
const INJECTED_ORIGINS: ReadonlySet<string> = new Set(['peer', 'task-notification']);

/** True when the turn's text opens with something the harness, a helper or Memnox added rather than the person. */
export function isInjectedPrompt(prompt: string): boolean {
  if (OPENING_TAG.test(firstLine(prompt) ?? '')) return true;
  // A hand-back's frame line can sit after a wrapper the host closed, so it is looked for once those are off.
  const said = firstLine(withoutHostTags(prompt));
  return said !== undefined && INJECTED_LINES.some((pattern) => pattern.test(said));
}

function firstLine(text: string): string | undefined {
  return text
    .split('\n')
    .map((line) => line.trim())
    .find((line) => line !== '');
}

/** Taken off until none is left, so a tag inside another cannot survive the pass that removed its outside. */
function withoutHostTags(said: string): string {
  let text = said;
  for (let before = ''; before !== text;) {
    before = text;
    text = withoutOneRoundOfHostTags(text);
  }
  return text;
}

/** True when a transcript entry's own origin says it came from a peer session or a task rather than the person. */
export function isInjectedOrigin(origin: unknown): boolean {
  if (origin === null || typeof origin !== 'object') return false;
  // Narrowed to an object just above; the field is checked before use.
  const { kind, handback } = origin as { kind?: unknown; handback?: unknown };
  if (handback === true) return true;
  return typeof kind === 'string' && INJECTED_ORIGINS.has(kind);
}

/**
 * Every tag the host wraps around what it adds, `<name ...>` to the first `</name>`, taken off with everything inside.
 * Found by index rather than one pattern, and every search is remembered, so a long or hostile turn costs its length.
 */
function withoutOneRoundOfHostTags(text: string): string {
  const lower = text.toLowerCase();
  const lastClose = new Map<string, number>();
  let kept = '';
  let from = 0;
  let nextGt = -1;
  for (let open = text.indexOf('<'); open !== -1; open = text.indexOf('<', open + 1)) {
    TAG_NAME.lastIndex = open + 1;
    const name = TAG_NAME.exec(text)?.[0].toLowerCase();
    if (name === undefined) continue;
    if (nextGt < TAG_NAME.lastIndex) nextGt = text.indexOf('>', TAG_NAME.lastIndex);
    if (nextGt === -1) break;
    const closer = `</${name}>`;
    if (!lastClose.has(name)) lastClose.set(name, lower.lastIndexOf(closer));
    if ((lastClose.get(name) ?? -1) <= nextGt) continue;
    const close = lower.indexOf(closer, nextGt + 1);
    kept += text.slice(from, open);
    from = close + closer.length;
    open = from - 1;
  }
  return kept + text.slice(from);
}
